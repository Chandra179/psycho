type MarotoPDFGenerator struct{}

func NewMarotoPDFGenerator() *MarotoPDFGenerator {
	return &MarotoPDFGenerator{}
}

func (g *MarotoPDFGenerator) Generate(p Profile) ([]byte, error) {
	cfg := config.NewBuilder().
		WithPageSize(pagesize.A4).
		WithLeftMargin(20).
		WithTopMargin(20).
		WithRightMargin(20).
		WithBottomMargin(20).
		WithAuthor("Psycho", false).
		WithTitle("Psychological Profile", false).
		Build()

	m := maroto.New(cfg)

	allTraits := []string{
		"openness", "conscientiousness", "extraversion", "agreeableness", "neuroticism",
		"regulatory_focus", "need_for_cognition", "cognitive_style", "need_for_closure",
	}

	m.AddRow(14, text.NewCol(12, "Psychological Profile",
		props.Text{Style: fontstyle.Bold, Size: 16, Align: align.Center}))
	m.AddRow(6, text.NewCol(12, fmt.Sprintf("Confidence level: %s  |  Analysis ID: %s", p.ConfidenceFlag, p.AnalysisID),
		props.Text{Size: 8, Align: align.Center}))
	m.AddRow(6, text.NewCol(12, "Generated by Psycho. Project-defined text proxies, not validated personality or clinical measures.",
		props.Text{Size: 7, Align: align.Center, Style: fontstyle.Italic}))

	m.AddRow(4, text.NewCol(12, ""))

	if p.Narrative != "" {
		g.renderNarrative(m, p.Narrative)
		m.AddRow(6, text.NewCol(12, ""))
	}

	m.AddRow(8, text.NewCol(12, "At a Glance", props.Text{Style: fontstyle.Bold, Size: 12}))
	m.AddRow(4, text.NewCol(12, ""))
	for _, name := range allTraits {
		t, ok := p.Traits[name]
		if !ok || len(t.ConfidenceInterval) < 2 {
			continue
		}
		m.AddRow(5, text.NewCol(12, fmt.Sprintf("%s: %s", analyze.DimensionDisplayName(name), analyze.DimensionLabel(name, t.Score)),
			props.Text{Size: 9}))
	}

	if len(p.Values) > 0 {
		m.AddRow(6, text.NewCol(12, ""))
		m.AddRow(8, text.NewCol(12, "Schwartz Value Orientation (ranked)",
			props.Text{Style: fontstyle.Bold, Size: 12}))
		m.AddRow(4, text.NewCol(12, ""))

		keys := make([]string, 0, len(p.Values))
		for k := range p.Values {
			keys = append(keys, k)
		}
		sort.Slice(keys, func(i, j int) bool {
			if p.Values[keys[i]] == p.Values[keys[j]] {
				return keys[i] < keys[j]
			}
			return p.Values[keys[i]] > p.Values[keys[j]]
		})
		for i, k := range keys {
			dn := analyze.ValueDisplayName(analyze.ValueCategory(k))
			m.AddRow(5, text.NewCol(12, fmt.Sprintf("%d. %s", i+1, dn), props.Text{Size: 9}))
		}
	}

	m.AddRow(6, text.NewCol(12, ""))
	m.AddRow(8, text.NewCol(12, "Summary Variables",
		props.Text{Style: fontstyle.Bold, Size: 12}))
	m.AddRow(4, text.NewCol(12, ""))
	sv := p.Summary
	m.AddRow(5, text.NewCol(12, fmt.Sprintf("Analytical Thinking: %s",
		analyze.SummaryBandFormal("analytical_thinking", sv.AnalyticalThinking)),
		props.Text{Size: 9}))
	m.AddRow(5, text.NewCol(12, fmt.Sprintf("Clout: %s",
		analyze.SummaryBandFormal("clout", sv.Clout)),
		props.Text{Size: 9}))
	m.AddRow(5, text.NewCol(12, fmt.Sprintf("Authenticity: %s",
		analyze.SummaryBandFormal("authenticity", sv.Authenticity)),
		props.Text{Size: 9}))
	m.AddRow(5, text.NewCol(12, fmt.Sprintf("Emotional Tone: %s", analyze.SummaryTone(sv.EmotionalTone)),
		props.Text{Size: 9}))

	m.AddRow(10, text.NewCol(12, ""))
	m.AddRow(8, text.NewCol(12, "Statistical Detail", props.Text{Style: fontstyle.Bold, Size: 12}))
	m.AddRow(4, text.NewCol(12, "Percentile is relative to the reference sample; the rough score range uses project-defined length and coverage assumptions, not a validated confidence interval.",
		props.Text{Size: 7, Style: fontstyle.Italic}))
	m.AddRow(4, text.NewCol(12, ""))
	for _, name := range allTraits {
		t, ok := p.Traits[name]
		if !ok || len(t.ConfidenceInterval) < 2 {
			continue
		}
		line := fmt.Sprintf("%s: %.2f, %s percentile (rough score range: %.2f–%.2f)",
			analyze.DimensionDisplayName(name), t.Score, analyze.Ordinal(t.Percentile), t.ConfidenceInterval[0], t.ConfidenceInterval[1])
		m.AddRow(5, text.NewCol(12, line, props.Text{Size: 7}))
	}

	m.AddRow(10, text.NewCol(12, ""))
	m.AddRow(8, text.NewCol(12, "Linguistic Evidence", props.Text{Style: fontstyle.Bold, Size: 12}))
	m.AddRow(4, text.NewCol(12, "Contribution = share of words in a dictionary category × per-percentage-point weight. Strongest contributors first.",
		props.Text{Size: 7, Style: fontstyle.Italic}))
	m.AddRow(4, text.NewCol(12, ""))
	for _, name := range allTraits {
		t, ok := p.Traits[name]
		if !ok || len(t.Evidence) == 0 {
			continue
		}
		m.AddRow(6, text.NewCol(12, analyze.DimensionDisplayName(name), props.Text{Size: 9}))
		for _, c := range t.Evidence {
			line := fmt.Sprintf("%s: %.1f%% of words × %+.3f/pp = %+.2f",
				c.Category, c.WordPercent, c.Weight, c.Contribution)
			m.AddRow(5, text.NewCol(12, "    "+line, props.Text{Size: 8}))
		}
	}

	doc, err := m.Generate()
	if err != nil {
		return nil, fmt.Errorf("generate pdf: %w", err)
	}
	return doc.GetBytes(), nil
}

// renderNarrative converts the narrative's lightweight Markdown (##/###
// headings, **bold** labels, - bullets, --- rules) into maroto rows.
// Maroto has no inline styling, so emphasis markers are stripped rather
// than printed literally.
func (g *MarotoPDFGenerator) renderNarrative(m core.Maroto, narrative string) {
	for _, line := range strings.Split(narrative, "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case trimmed == "":
			continue
		case strings.HasPrefix(trimmed, "### "):
			m.AddRow(6, text.NewCol(12, strings.TrimPrefix(trimmed, "### "),
				props.Text{Style: fontstyle.Bold, Size: 11}))
		case strings.HasPrefix(trimmed, "## "):
			m.AddRow(8, text.NewCol(12, strings.TrimPrefix(trimmed, "## "),
				props.Text{Style: fontstyle.Bold, Size: 12}))
		case trimmed == "---":
			m.AddRow(3, text.NewCol(12, ""))
		case strings.HasPrefix(trimmed, "- "):
			m.AddAutoRow(text.NewCol(12, "• "+stripEmphasis(strings.TrimPrefix(trimmed, "- ")),
				props.Text{Size: 9}))
		default:
			m.AddAutoRow(text.NewCol(12, stripEmphasis(trimmed), props.Text{Size: 9}))
		}
	}
}

func stripEmphasis(s string) string {
	s = strings.ReplaceAll(s, "**", "")
	return strings.ReplaceAll(s, "*", "")
}
